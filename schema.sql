CREATE TABLE IF NOT EXISTS panels (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  panel_code VARCHAR(64) NOT NULL UNIQUE,
  connect_token VARCHAR(64) NOT NULL UNIQUE,
  duration INTEGER NOT NULL DEFAULT 30,
  expires_at TIMESTAMPTZ,
  is_active SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(255) NOT NULL,
  username VARCHAR(100) NOT NULL UNIQUE,
  password VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'RESELLER' CHECK (role IN ('OWNER','ADMIN','RESELLER')),
  balance INTEGER NOT NULL DEFAULT 0,
  validity TIMESTAMPTZ,
  panel_code VARCHAR(64) NOT NULL,
  is_blocked SMALLINT NOT NULL DEFAULT 0,
  invited_by INTEGER,
  can_generate_referral SMALLINT NOT NULL DEFAULT 1,
  referral_limit INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS users_panel_code_idx ON users(panel_code);
CREATE INDEX IF NOT EXISTS users_invited_by_idx ON users(invited_by);

CREATE TABLE IF NOT EXISTS referrals (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(64) NOT NULL UNIQUE,
  role VARCHAR(20) NOT NULL,
  duration INTEGER NOT NULL,
  balance INTEGER NOT NULL DEFAULT 0,
  panel_code VARCHAR(64) NOT NULL,
  created_by INTEGER NOT NULL,
  used SMALLINT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS referrals_panel_code_idx ON referrals(panel_code);
CREATE INDEX IF NOT EXISTS referrals_created_by_idx ON referrals(created_by);

CREATE TABLE IF NOT EXISTS api_keys (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key_value VARCHAR(255) NOT NULL UNIQUE,
  duration VARCHAR(20) NOT NULL,
  device_limit INTEGER NOT NULL DEFAULT 1,
  panel_code VARCHAR(64) NOT NULL,
  created_by INTEGER NOT NULL,
  uses INTEGER NOT NULL DEFAULT 0,
  expires_at TIMESTAMPTZ,
  is_blocked SMALLINT NOT NULL DEFAULT 0,
  is_active SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS api_keys_panel_code_idx ON api_keys(panel_code);
CREATE INDEX IF NOT EXISTS api_keys_created_by_idx ON api_keys(created_by);

CREATE TABLE IF NOT EXISTS key_devices (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  key_id INTEGER NOT NULL,
  device_uuid VARCHAR(255) NOT NULL,
  panel_code VARCHAR(64) NOT NULL,
  last_seen TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_key_device UNIQUE(key_id, device_uuid)
);
CREATE INDEX IF NOT EXISTS key_devices_panel_code_idx ON key_devices(panel_code);

CREATE TABLE IF NOT EXISTS mod_settings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  setting_name VARCHAR(100) NOT NULL,
  setting_value TEXT,
  panel_code VARCHAR(64) NOT NULL,
  CONSTRAINT uq_setting UNIQUE(setting_name, panel_code)
);
CREATE INDEX IF NOT EXISTS mod_settings_panel_code_idx ON mod_settings(panel_code);

CREATE TABLE IF NOT EXISTS mod_maintenance (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  panel_code VARCHAR(64) NOT NULL UNIQUE,
  is_active SMALLINT NOT NULL DEFAULT 0,
  reason VARCHAR(500)
);
